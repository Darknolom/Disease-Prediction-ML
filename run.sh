#!/bin/bash
# ============================================================
# Bash-скрипт для запуска ML-пайплайна предсказания заболеваний
# ============================================================
# Параметры (Пункт 8 задания — не менее двух):
#   $1 — имя модели (logistic_regression, decision_tree, knn,
#        random_forest, gradient_boosting, xgboost, all)
#   $2 — значение random seed
#   $3 — путь к данным
#   $4 — путь к выходному каталогу результатов
# ============================================================

MODEL_NAME=${1:-"xgboost"}
SEED=${2:-42}
DATA_DIR=${3:-"./data"}
OUTPUT_DIR=${4:-"./results"}
MODEL_DIR="./models"

echo "============================================================"
echo "  ЗАПУСК ML-ПАЙПЛАЙНА"
echo "============================================================"
echo "  Модель:        $MODEL_NAME"
echo "  Random Seed:   $SEED"
echo "  Данные:        $DATA_DIR"
echo "  Результаты:    $OUTPUT_DIR"
echo "  Модели:        $MODEL_DIR"
echo "============================================================"

# Автоматическое создание каталогов (Пункт 9)
mkdir -p "$OUTPUT_DIR"
mkdir -p "$MODEL_DIR"

# Запуск через uv (использует окружение из pyproject.toml)
uv run python src/main.py \
    --model "$MODEL_NAME" \
    --seed "$SEED" \
    --data_dir "$DATA_DIR" \
    --output_dir "$OUTPUT_DIR" \
    --model_dir "$MODEL_DIR"

echo ""
echo "============================================================"
echo "  ЗАВЕРШЕНО. Результаты в: $OUTPUT_DIR"
echo "============================================================"
